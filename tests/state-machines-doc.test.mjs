// tests/state-machines-doc.test.mjs — generated docs/STATE-MACHINES.md (STATE-MACHINES-PLAN Phase 5.2):
// the checked-in file is fresh, every registry machine has a heading, generation is deterministic,
// and --check fails (naming the file) on tamper or registry drift, using temp roots as controls.
import { pass, fail, warn, NODE, ROOT } from './helpers.mjs';
import { spawnSync } from 'child_process';
import { mkdtempSync, writeFileSync, readFileSync, cpSync, rmSync, existsSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import { listMachines } from '../lib/state-machine.mjs';
import { WHOLE_FILE_DOCS } from '../gen-machine-docs.mjs';

console.log('\ngenerated docs/STATE-MACHINES.md (gen-machine-docs whole-file target)');

const GEN = join(ROOT, 'gen-machine-docs.mjs');
const REL = 'docs/STATE-MACHINES.md';
const run = (args, cwd = ROOT) => spawnSync(NODE, [GEN, ...args], { encoding: 'utf-8', timeout: 60_000, cwd });
const norm = s => s.replace(/\r\n/g, '\n');
const render = root => WHOLE_FILE_DOCS.find(d => d.file === REL).render(root);
const headings = text => norm(text).split('\n').filter(l => l.startsWith('## ')).map(l => l.slice(3));

// ── 1. The checked-in file is present and fresh ────────────────────
const checkedIn = join(ROOT, REL);
if (!existsSync(checkedIn)) fail(`${REL} is missing — run: node gen-machine-docs.mjs`);
else {
  const text = norm(readFileSync(checkedIn, 'utf-8'));
  text === render(ROOT) ? pass(`${REL} exists and equals the registry-derived render`) : fail(`${REL} is stale — run: node gen-machine-docs.mjs`);
  const r = run(['--check', REL]);
  r.status === 0 ? pass(`gen-machine-docs --check ${REL} is clean`) : fail(`--check ${REL} exit ${r.status}: ${r.stderr.trim()}`);
}

// ── 2. Every registry machine is a heading (identity, not count) ───
{
  const ids = listMachines();
  const hs = headings(readFileSync(checkedIn, 'utf-8'));
  const missing = ids.filter(id => !hs.includes(id));
  const extra = hs.filter(h => h !== 'Index' && !ids.includes(h));
  missing.length === 0 ? pass(`all ${ids.length} registry machine ids appear as headings`) : fail(`machines missing a heading: ${missing.join(', ')}`);
  extra.length === 0 ? pass('no machine heading names an unknown machine') : fail(`headings with no registry machine: ${extra.join(', ')}`);
}

// ── 3. Deterministic output: LF only, banner, no timestamps ────────
{
  const a = render(ROOT), b = render(ROOT);
  a === b ? pass('two renders are byte-identical') : fail('render is not deterministic');
  !a.includes('\r') ? pass('render uses LF newlines only') : fail('render contains CR characters');
  a.split('\n').slice(0, 4).some(l => l.includes('GENERATED by `node gen-machine-docs.mjs` — do not edit')) ? pass('top banner names the generator') : fail('banner missing from first lines');
}

// ── 4. Controls on a temp root ─────────────────────────────────────
const tmp = mkdtempSync(join(tmpdir(), 'state-machines-doc-'));
try {
  let ok = true;
  try { cpSync(join(ROOT, 'templates'), join(tmp, 'templates'), { recursive: true }); } catch (e) { ok = false; warn(`temp root could not be built (${e.message}) — doc controls not verified`); }
  if (ok) {
    const file = join(tmp, REL);
    const chkMissing = run(['--root', tmp, '--check', REL]);
    chkMissing.status === 1 && chkMissing.stderr.includes(REL)
      ? pass('control: --check on a missing doc exits 1 and names the file')
      : fail(`missing doc: exit ${chkMissing.status} ${chkMissing.stderr}`);

    const gen = run(['--root', tmp, REL]);
    gen.status === 0 && norm(readFileSync(file, 'utf-8')) === render(tmp)
      ? pass('write mode creates the doc from the temp registry')
      : fail(`write mode: exit ${gen.status} ${gen.stderr}`);
    run(['--root', tmp, '--check', REL]).status === 0 ? pass('control: --check passes on the freshly written doc') : fail('--check failed on fresh doc');

    // Tamper: a hand edit must be caught and named.
    const fresh = readFileSync(file, 'utf-8');
    writeFileSync(file, fresh + 'hand edit\n');
    const tampered = run(['--root', tmp, '--check', REL]);
    tampered.status === 1 && tampered.stderr.includes(REL)
      ? pass('tampered doc: --check exits 1 and names the file')
      : fail(`tampered doc not caught: exit ${tampered.status} ${tampered.stderr}`);
    const untouched = readFileSync(file, 'utf-8') === fresh + 'hand edit\n';
    untouched ? pass('--check never rewrites the tampered doc') : fail('--check rewrote the file');

    // CRLF checkout (autocrlf) of a fresh doc is not stale.
    writeFileSync(file, fresh.replace(/\n/g, '\r\n'));
    run(['--root', tmp, '--check', REL]).status === 0
      ? pass('control: a CRLF copy of a fresh doc is not reported stale')
      : fail('CRLF copy of fresh doc reported stale');

    // Registry drift makes the doc stale.
    const yml = join(tmp, 'templates', 'states.yml');
    const ymlOrig = readFileSync(yml, 'utf-8');
    writeFileSync(yml, ymlOrig.replace('Application submitted', 'Application sent in'));
    const drift = run(['--root', tmp, '--check', REL]);
    drift.status === 1 && drift.stderr.includes(REL)
      ? pass('registry drift makes the doc stale and --check names it')
      : fail(`registry drift not detected: exit ${drift.status} ${drift.stderr}`);
    writeFileSync(yml, ymlOrig);

    // Default --check over the temp root also covers the whole file.
    writeFileSync(file, fresh);
    run(['--root', tmp, '--check']).status === 0 ? pass('default --check includes the whole-file doc (fresh root passes)') : fail('default --check failed on fresh temp root');
    rmSync(file);
    const defMissing = run(['--root', tmp, '--check']);
    defMissing.status === 1 && defMissing.stderr.includes(REL)
      ? pass('default --check names a missing whole-file doc')
      : fail(`default --check missed the missing doc: exit ${defMissing.status}`);
  }
} finally { rmSync(tmp, { recursive: true, force: true }); }
